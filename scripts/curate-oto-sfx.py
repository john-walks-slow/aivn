def dur(path: Path) -> int:
    try:
        out = subprocess.run(
            ["ffprobe", "-v", "error", "-show_entries", "format=duration",
             "-of", "default=nw=1:nk=1", str(path)],
            capture_output=True, text=True, timeout=30,
        ).stdout.strip()
        return int(float(out)) if out else 0
    except Exception:
        return 0

made = skipped = 0
for zp in sorted(SRC.glob("se_zip_*.zip")):
    stem = zp.stem.replace("se_zip_", "")
    if stem not in REG:
        print(f"  跳过未登记: {stem}")
        skipped += 1
        continue
    eid, title, desc, tags, mood, scene, vol = REG[stem]
    entry = DST / eid
    if entry.exists():
        print(f"  已存在: {eid}")
        continue
    entry.mkdir(parents=True, exist_ok=True)
    # zip 里挑第一个 mp3（通常就一个）
    with zipfile.ZipFile(zp) as zf:
        mps = [n for n in zf.namelist() if n.lower().endswith(".mp3")]
        if not mps:
            print(f"  无 mp3: {stem}")
            shutil.rmtree(entry, ignore_errors=True)
            continue
        mps.sort(key=len)
        dst = entry / f"{eid}.mp3"
        with zf.open(mps[0]) as src, open(dst, "wb") as out:
            shutil.copyfileobj(src, out)
    d = dur(dst)
    meta = {
        "title": title,
        "description": desc,
        "tags": tags,
        "source": SOURCE,
        "sourceUrl": PAGE + stem.lower() + ".html",
        "license": "CC BY 4.0",
        "licenseUrl": TERMS,
        "attribution": "SE by OtoLogic(https://otologic.jp)",
        "mood": mood,
        "scene": scene,
        "durationSec": d,
        "loop": False,
        "volume": vol,
    }
    (entry / "meta.json").write_text(json.dumps(meta, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"  {eid}  {d}s  {dst.stat().st_size // 1024}KB")
    made += 1

print(f"\n入库 {made} 条 SFX，跳过 {skipped} 条未登记")
